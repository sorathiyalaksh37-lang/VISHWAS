import sqlite3
conn = sqlite3.connect('vishwas.db')
cur = conn.cursor()
cur.execute("SELECT name FROM sqlite_master WHERE type='table'")
print('Tables:', cur.fetchall())
cur.execute('PRAGMA table_info(analysis_reports)')
print('analysis_reports columns:', cur.fetchall())
cur.execute('PRAGMA table_info(call_records)')
print('call_records columns:', cur.fetchall())
conn.close()
